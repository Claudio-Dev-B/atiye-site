    /* ── Engine ───────────────────────────────────────────── */
  var lang = localStorage.getItem('atiye-lang') || 'pt-BR';

  function t(key) {
    return (T[lang] && T[lang][key]) || (T['pt-BR'] && T['pt-BR'][key]) || key;
  }

  function resetSplit(el) {
    if (el.dataset.split) {
      delete el.dataset.split;
      el.classList.remove('word-split', 'active');
    }
  }

  function reSplit(el) {
    if (!el) return;
    var words = el.textContent.trim().split(/\s+/);
    el.innerHTML = words.map(function (w, i) {
      return '<span class="word"><span class="word-inner" style="--i:' + i + '">' + w + '</span></span>';
    }).join(' ');
    el.dataset.split = '1';
    el.classList.add('word-split', 'active');
  }

  function apply() {
    /* plain text */
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var val = t(el.getAttribute('data-i18n'));
      if (!val) return;
      resetSplit(el);
      el.textContent = val;
      if (el.classList.contains('hero-title') || el.classList.contains('section-title')) {
        reSplit(el);
      }
    });

    /* inner HTML (elements with <br> <em> <strong>) */
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var val = t(el.getAttribute('data-i18n-html'));
      if (!val) return;
      resetSplit(el);
      el.innerHTML = val;
    });

    /* placeholder */
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var val = t(el.getAttribute('data-i18n-placeholder'));
      if (val) el.setAttribute('placeholder', val);
    });

    /* meta description */
    var metaEl = document.querySelector('meta[name="description"]');
    var metaKey = document.documentElement.dataset.i18nMeta;
    if (metaEl && metaKey) metaEl.setAttribute('content', t(metaKey));

    /* page title */
    var titleKey = document.documentElement.dataset.i18nTitle;
    if (titleKey) document.title = t(titleKey);

    /* aria-label */
    document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
      var val = t(el.getAttribute('data-i18n-aria-label'));
      if (val) el.setAttribute('aria-label', val);
    });

    /* html lang */
    document.documentElement.lang = lang;

    /* toggle button state */
    var btn = document.getElementById('lang-toggle');
    if (btn) {
      btn.querySelector('.lang-pt').classList.toggle('lang-active', lang === 'pt-BR');
      btn.querySelector('.lang-en').classList.toggle('lang-active', lang === 'en');
    }
  }

  function loadEN(cb) {
    if (T['en']) { cb(); return; }
    if (window._atiyeEN) { T['en'] = window._atiyeEN; cb(); return; }
    var s = document.createElement('script');
    s.src = 'translations-en.js?v=20260629';
    s.onload = function () { T['en'] = window._atiyeEN || {}; cb(); };
    document.head.appendChild(s);
  }

  function toggle() {
    lang = lang === 'pt-BR' ? 'en' : 'pt-BR';
    localStorage.setItem('atiye-lang', lang);
    if (lang === 'en') { loadEN(apply); } else { apply(); }
  }

  /* ── Init ─────────────────────────────────────────────── */
  function init() {
    var btn = document.getElementById('lang-toggle');
    if (btn) btn.addEventListener('click', toggle);
    if (lang === 'en') { loadEN(apply); } else { apply(); }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  /* ── Public API ───────────────────────────────────────── */
  window.atiyeT = { t: t, getLang: function () { return lang; } };

